// Runs OCaml command-line programs compiled to WasmGC with wasm_of_ocaml (see
// build.sh). The loader generated by wasm_of_ocaml only supports command-line
// arguments, exit codes and file output when running under Node.js, so this
// file provides a minimal Node.js-like environment (`process`, `require`,
// `module`) backed by an in-memory file system. Each run creates a new instance
// of the program; the Wasm module is compiled once, in the first iteration.

class OCamlMemFS {
    constructor() {
        this.files = new Map(); // path -> Uint8Array
        this.fds = new Map(); // fd -> { path, data, length, position, append, writable }
        this.nextFd = 3;
        this.stdout = [];
        this.stderr = [];
        this.constants = {
            R_OK: 4,
            W_OK: 2,
            X_OK: 1,
            F_OK: 0,
            O_RDONLY: 0,
            O_WRONLY: 1,
            O_RDWR: 2,
            O_CREAT: 0o100,
            O_EXCL: 0o200,
            O_NOCTTY: 0o400,
            O_TRUNC: 0o1000,
            O_APPEND: 0o2000,
            O_NONBLOCK: 0o4000,
            O_DSYNC: 0o10000,
            O_SYNC: 0o4010000,
        };
    }

    reset(files) {
        this.files = new Map(files.map(([path, data]) => [this.normalize(path), data]));
        this.fds.clear();
        this.nextFd = 3;
        this.stdout = [];
        this.stderr = [];
    }

    error(code, syscall, path) {
        const message = { ENOENT: "no such file or directory", EBADF: "bad file descriptor" }[code];
        return Object.assign(new Error(`${code}: ${message}, ${syscall} '${path}'`), {
            code,
            syscall,
            path,
        });
    }

    // Paths relative to the current directory (the root), without "." or ".."
    // components.
    normalize(path) {
        const parts = [];
        for (const part of String(path).split("/")) {
            if (part === "" || part === ".") continue;
            if (part === "..") parts.pop();
            else parts.push(part);
        }
        return parts.join("/");
    }

    isDirectory(path) {
        path = this.normalize(path);
        const prefix = path === "" ? "" : path + "/";
        for (const name of this.files.keys()) if (name.startsWith(prefix)) return true;
        return false;
    }

    fd(fd) {
        const file = this.fds.get(fd);
        if (!file) throw this.error("EBADF", "fd", fd);
        return file;
    }

    // Output is stored as soon as it is written, since programs may exit
    // without closing their output channels.
    commit(file) {
        this.files.set(file.path, file.data.subarray(0, file.length));
    }

    openSync(path, flags) {
        path = this.normalize(path);
        const { O_CREAT, O_TRUNC, O_APPEND, O_WRONLY, O_RDWR } = this.constants;
        let data = this.files.get(path);
        if (!data && !(flags & O_CREAT)) throw this.error("ENOENT", "open", path);
        if (!data || flags & O_TRUNC) data = new Uint8Array(0);
        else if (flags & (O_WRONLY | O_RDWR)) data = data.slice(); // Inputs are shared between runs.
        const file = {
            path,
            data,
            length: data.length,
            position: 0,
            append: !!(flags & O_APPEND),
            writable: !!(flags & (O_WRONLY | O_RDWR)),
        };
        if (file.writable) this.commit(file);
        const fd = this.nextFd++;
        this.fds.set(fd, file);
        return fd;
    }

    closeSync(fd) {
        this.fd(fd);
        this.fds.delete(fd);
    }

    writeSync(fd, buffer, offset, length, position) {
        if (fd === 1 || fd === 2) {
            (fd === 1 ? this.stdout : this.stderr).push(buffer.slice(offset, offset + length));
            return length;
        }
        const file = this.fd(fd);
        let start = file.append ? file.length : position == null ? file.position : Number(position);
        const end = start + length;
        if (end > file.data.length) {
            const data = new Uint8Array(Math.max(2 * file.data.length, end, 4096));
            data.set(file.data.subarray(0, file.length));
            file.data = data;
        }
        file.data.set(buffer.subarray(offset, offset + length), start);
        file.length = Math.max(file.length, end);
        if (position == null) file.position = end;
        this.commit(file);
        return length;
    }

    readSync(fd, buffer, offset, length, position) {
        const file = this.fd(fd);
        const start = position == null ? file.position : Number(position);
        const count = Math.max(0, Math.min(length, file.length - start));
        buffer.set(file.data.subarray(start, start + count), offset);
        if (position == null) file.position = start + count;
        return count;
    }

    fstatSync(fd) {
        return { size: BigInt(this.fd(fd).length) };
    }

    existsSync(path) {
        path = this.normalize(path);
        return this.files.has(path) || this.isDirectory(path);
    }

    statSync(path) {
        path = this.normalize(path);
        const isFile = this.files.has(path);
        if (!isFile && !this.isDirectory(path)) throw this.error("ENOENT", "stat", path);
        return {
            isFile: () => isFile,
            isDirectory: () => !isFile,
            isCharacterDevice: () => false,
            isBlockDevice: () => false,
            isSymbolicLink: () => false,
            isFIFO: () => false,
            isSocket: () => false,
            dev: 0,
            ino: 0,
            mode: isFile ? 0o100644 : 0o40755,
            nlink: 1,
            uid: 0,
            gid: 0,
            rdev: 0,
            size: isFile ? this.files.get(path).length : 0,
            atimeMs: 0,
            mtimeMs: 0,
            ctimeMs: 0,
        };
    }

    lstatSync(path) {
        return this.statSync(path);
    }

    readdirSync(path) {
        path = this.normalize(path);
        const prefix = path === "" ? "" : path + "/";
        const names = new Set();
        for (const name of this.files.keys())
            if (name.startsWith(prefix)) names.add(name.slice(prefix.length).split("/")[0]);
        if (names.size === 0) throw this.error("ENOENT", "scandir", path);
        return [...names];
    }

    unlinkSync(path) {
        path = this.normalize(path);
        if (!this.files.delete(path)) throw this.error("ENOENT", "unlink", path);
    }

    renameSync(from, to) {
        from = this.normalize(from);
        to = this.normalize(to);
        if (!this.files.has(from)) throw this.error("ENOENT", "rename", from);
        this.files.set(to, this.files.get(from));
        this.files.delete(from);
    }
}

const ocamlFS = new OCamlMemFS();
let currentOCamlProgram = null;

// The Node.js APIs used by the wasm_of_ocaml loader.
globalThis.process = {
    versions: { node: "jetstream" },
    platform: "linux",
    arch: "x64",
    argv: [],
    env: {},
    exitCode: 0,
    exit(code) {
        this.exitCode = code;
    },
    cwd: () => "/",
    on() {},
};
globalThis.module = { filename: "/ocaml.js" };
globalThis.require = (name) => {
    switch (name) {
        case "node:fs":
            return new Proxy(ocamlFS, {
                get(target, property) {
                    if (!(property in target))
                        throw new Error(`fs.${String(property)} is not supported`);
                    const value = target[property];
                    return typeof value === "function" ? value.bind(target) : value;
                },
            });
        case "node:path":
            return {
                join: (...parts) => parts.join("/"),
                dirname: (path) => path.slice(0, Math.max(0, path.lastIndexOf("/"))) || ".",
            };
        case "node:fs/promises":
            return {
                readFile: async (path) => {
                    if (!path.endsWith(".wasm")) throw new Error(`Unexpected file read: ${path}`);
                    return currentOCamlProgram.wasmBinary;
                },
            };
        case "node:tty":
            return { isatty: () => false };
    }
    throw new Error(`Module ${name} is not supported`);
};

// Used by Random.self_init; some shells do not provide it.
if (typeof crypto === "undefined") {
    globalThis.crypto = {
        getRandomValues(array) {
            for (let i = 0; i < array.length; i++) array[i] = Math.imul(i + 1, 0x9e3779b1);
            return array;
        },
    };
}

// Compile each program once and instantiate it for every run.
const originalInstantiate = WebAssembly.instantiate;
WebAssembly.instantiate = async function (source, imports, options) {
    const program = currentOCamlProgram;
    if (!program || source !== program.wasmBinary)
        return originalInstantiate.call(WebAssembly, source, imports, options);
    program.module ??= await WebAssembly.compile(source, options);
    const instance = await originalInstantiate.call(WebAssembly, program.module, imports);
    return { module: program.module, instance };
};

// Concatenation of the chunks, without the lines starting with one of the
// given prefixes.
function filterLines(chunks, prefixes) {
    const bytes = new Uint8Array(chunks.reduce((length, chunk) => length + chunk.length, 0));
    let offset = 0;
    for (const chunk of chunks) {
        bytes.set(chunk, offset);
        offset += chunk.length;
    }
    const text = new TextDecoder().decode(bytes);
    const lines = text.split("\n").filter((line) => !prefixes.some((prefix) => line.startsWith(prefix)));
    return [new TextEncoder().encode(lines.join("\n"))];
}

function fnv1a(chunks) {
    let hash = 0x811c9dc5;
    let length = 0;
    for (const chunk of chunks) {
        for (let i = 0; i < chunk.length; i++) hash = Math.imul(hash ^ chunk[i], 0x01000193) >>> 0;
        length += chunk.length;
    }
    return `${length}:${hash.toString(16).padStart(8, "0")}`;
}

function asUint8Array(array) {
    return new Uint8Array(array.buffer, array.byteOffset, array.byteLength);
}

class OCamlProgram {
    constructor(name, description) {
        this.name = name;
        this.description = description;
        this.module = null;
        this.output = null;
    }

    async init() {
        const preload = JetStream.preload;
        this.loaderSource = await JetStream.getString(preload[this.description.loader]);
        this.wasmBinary = asUint8Array(await JetStream.getBinary(preload[this.description.wasm]));
        this.inputs = [];
        for (const [path, key] of Object.entries(this.description.files))
            this.inputs.push([path, asUint8Array(await JetStream.getBinary(preload[key]))]);
        // A bundle is a JSON object mapping paths to the contents of text files.
        if (this.description.bundle) {
            const bundle = JSON.parse(await JetStream.getString(preload[this.description.bundle]));
            const encoder = new TextEncoder();
            for (const [path, text] of Object.entries(bundle)) this.inputs.push([path, encoder.encode(text)]);
        }
    }

    async run() {
        ocamlFS.reset(this.inputs);
        process.argv = ["node", this.name, ...this.description.argv];
        process.env = { ...this.description.env };
        process.exitCode = 0;
        currentOCamlProgram = this;
        try {
            // The loader is a script which instantiates and runs the program, and
            // evaluates to a promise.
            await (0, eval)(this.loaderSource);
        } finally {
            currentOCamlProgram = null;
        }
        if (process.exitCode !== 0) {
            const stderr = new TextDecoder().decode(
                new Uint8Array(ocamlFS.stderr.flatMap((chunk) => [...chunk]))
            );
            throw new Error(`${this.name} exited with code ${process.exitCode}: ${stderr}`);
        }
        const output = this.description.output;
        this.output = output === "<stdout>" ? ocamlFS.stdout : [ocamlFS.files.get(output) ?? []];
    }

    validate() {
        const ignore = this.description.ignore;
        const checksum = fnv1a(ignore ? filterLines(this.output, ignore) : this.output);
        if (checksum !== this.description.expected)
            throw new Error(
                `${this.name}: unexpected output (checksum ${checksum}, expected ${this.description.expected})`
            );
    }
}

class Benchmark {
    constructor({ workloads }) {
        this.workloadNames = workloads;
    }

    async init() {
        const manifest = JSON.parse(await JetStream.getString(JetStream.preload.manifest));
        this.programs = this.workloadNames.map((name) => new OCamlProgram(name, manifest[name]));
        for (const program of this.programs) await program.init();
    }

    async runIteration() {
        for (const program of this.programs) await program.run();
    }

    validate() {
        for (const program of this.programs) program.validate();
    }
}
